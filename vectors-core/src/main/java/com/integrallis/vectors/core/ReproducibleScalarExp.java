package com.integrallis.vectors.core;

/**
 * Computes the exact float cast of {@link StrictMath#exp(double)} while permitting the JDK's
 * intrinsified {@link Math#exp(double)} away from ambiguous float-rounding boundaries.
 *
 * <p>StrictMath.exp has mandated fdlibm semantics; both methods are within one double ulp.
 * Exhaustive enumeration of every float magnitude in [2^-28, 104], using eight neighboring doubles
 * on each side of the StrictMath result, finds only the 15 inputs below whose interval straddles a
 * float rounding boundary. Every such input takes StrictMath. A conservative bucket table also
 * sends harmless collisions there, avoiding a large sparse switch in the hot path. All inputs
 * outside the certified interval, including nonfinite values, take StrictMath directly.
 *
 * <p>The generator, complete catalogue, interval proof, and validation instructions are retained in
 * {@code experiments/convolution-exp-catalogue}. Do not replace the catalogue with observed
 * Math/StrictMath disagreements: it must cover every result allowed by the accuracy bound.
 */
final class ReproducibleScalarExp {
  private ReproducibleScalarExp() {}

  private static final int MIN_CERTIFIED_MAGNITUDE = 0x31800000; // 2^-28
  private static final int MAX_CERTIFIED_MAGNITUDE = 0x42d00000; // 104
  private static final boolean[] EXCEPTION_BUCKETS = buildExceptionBuckets();

  static float exp(float value) {
    int raw = Float.floatToRawIntBits(value);
    int magnitude = raw & 0x7fffffff;
    if (magnitude < MIN_CERTIFIED_MAGNITUDE
        || magnitude > MAX_CERTIFIED_MAGNITUDE
        || EXCEPTION_BUCKETS[(raw * 0x9e3779b9) >>> 21]) {
      return (float) StrictMath.exp((double) value);
    }
    return (float) Math.exp((double) value);
  }

  private static boolean[] buildExceptionBuckets() {
    boolean[] buckets = new boolean[2048];
    // Generated by EnumerateExpExceptions.java with the frozen eight-double-neighbor bound.
    int[] catalogue = {
      0xb3000000, 0x33800000, 0x36fdffc1, 0x377eff81, 0x383a3ef1,
      0x38e69cc1, 0x39c6be5b, 0x39e5bb1d, 0xbae0e25c, 0xbbf0edf1,
      0x3d1a274e, 0x4001b249, 0x40315b33, 0xc16912cd, 0x4288942b
    };
    for (int raw : catalogue) buckets[(raw * 0x9e3779b9) >>> 21] = true;
    return buckets;
  }
}
