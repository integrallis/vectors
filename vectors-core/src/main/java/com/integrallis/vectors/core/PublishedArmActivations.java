  static final float RLOG2 = 1.442695040888963407359924681001892137426645954152985934135449406931f;
  static final float C5 = (float) 0.000198527617612853646278381;
  static final float C4 = (float) 0.00139304355252534151077271;
  static final float C3 = (float) 0.00833336077630519866943359;
  static final float C2 = (float) 0.0416664853692054748535156;
  static final float C1 = (float) 0.166666671633720397949219;
  static final float LNHI = 0.69314718246459960938f;
  static final float LNLO = -1.904654323148236017e-09f;

  static void swiGlu(
      float[] out,
      int outOffset,
      float[] gate,
      int gateOffset,
      float[] up,
      int upOffset,
      int length) {
    int index = 0;
    int limit = FloatVector.SPECIES_128.loopBound(length);
    FloatVector one = FloatVector.broadcast(FloatVector.SPECIES_128, 1.0f);
    for (; index < limit; index += FloatVector.SPECIES_128.length()) {
      FloatVector value = FloatVector.fromArray(FloatVector.SPECIES_128, gate, gateOffset + index);
      FloatVector multiplier = FloatVector.fromArray(FloatVector.SPECIES_128, up, upOffset + index);
      FloatVector swiExp;
      {
        FloatVector d = value.neg();

        var fs = d.species();
        FloatVector a =
            d.blend(
                0f, d.abs().compare(VectorOperators.GT, 104f).or(d.test(VectorOperators.IS_NAN)));
        FloatVector product = a.mul(RLOG2);
        IntVector sign = product.reinterpretAsInts().and(0x80000000);
        FloatVector rangeBias = sign.or(Float.floatToRawIntBits(0x1.8p23f)).reinterpretAsFloats();
        IntVector q =
            (IntVector) product.add(rangeBias).sub(rangeBias).convert(VectorOperators.F2I, 0);
        FloatVector fq = (FloatVector) q.convert(VectorOperators.I2F, 0);
        FloatVector s = fq.fma(FloatVector.broadcast(fs, -0.693145751953125f), a);
        s = fq.fma(FloatVector.broadcast(fs, -1.428606765330187045e-06f), s);
        FloatVector u = FloatVector.broadcast(fs, C5).fma(s, FloatVector.broadcast(fs, C4));
        u = u.fma(s, FloatVector.broadcast(fs, C3));
        u = u.fma(s, FloatVector.broadcast(fs, C2));
        u = u.fma(s, FloatVector.broadcast(fs, C1));
        u = u.fma(s, FloatVector.broadcast(fs, 0.5f));
        u = s.mul(s).fma(u, s).add(1f);
        IntVector half = q.lanewise(VectorOperators.ASHR, 1);
        u = u.mul(half.add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.mul(q.sub(half).add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.blend(0f, d.compare(VectorOperators.LT, -104f));
        u = u.blend(Float.POSITIVE_INFINITY, d.compare(VectorOperators.GT, 100f));
        swiExp = u.blend(d.add(d), d.test(VectorOperators.IS_NAN));
      }
      value.div(one.add(swiExp)).mul(multiplier).intoArray(out, outOffset + index);
    }
    for (; index < length; index++) {
      float value = gate[gateOffset + index];
      out[outOffset + index] = value / (1.0f + scalarExp(-value)) * up[upOffset + index];
    }
  }

  static void sigmoidAndScaledSoftplus(
      float[] sigmoidValues,
      int sigmoidOffset,
      float[] softplusValues,
      int softplusOffset,
      float[] bias,
      int biasOffset,
      float[] scale,
      int scaleOffset,
      float[] scaledSoftplus,
      int scaledSoftplusOffset,
      int length) {
    int index = 0;
    int limit = FloatVector.SPECIES_128.loopBound(length);
    FloatVector one = FloatVector.broadcast(FloatVector.SPECIES_128, 1.0f);
    FloatVector threshold = FloatVector.broadcast(FloatVector.SPECIES_128, 20.0f);
    for (; index < limit; index += FloatVector.SPECIES_128.length()) {
      FloatVector sigmoid =
          FloatVector.fromArray(FloatVector.SPECIES_128, sigmoidValues, sigmoidOffset + index);
      FloatVector sigmoidExp;
      {
        FloatVector d = sigmoid.neg();

        var fs = d.species();
        FloatVector a =
            d.blend(
                0f, d.abs().compare(VectorOperators.GT, 104f).or(d.test(VectorOperators.IS_NAN)));
        FloatVector product = a.mul(RLOG2);
        IntVector sign = product.reinterpretAsInts().and(0x80000000);
        FloatVector rangeBias = sign.or(Float.floatToRawIntBits(0x1.8p23f)).reinterpretAsFloats();
        IntVector q =
            (IntVector) product.add(rangeBias).sub(rangeBias).convert(VectorOperators.F2I, 0);
        FloatVector fq = (FloatVector) q.convert(VectorOperators.I2F, 0);
        FloatVector s = fq.fma(FloatVector.broadcast(fs, -0.693145751953125f), a);
        s = fq.fma(FloatVector.broadcast(fs, -1.428606765330187045e-06f), s);
        FloatVector u = FloatVector.broadcast(fs, C5).fma(s, FloatVector.broadcast(fs, C4));
        u = u.fma(s, FloatVector.broadcast(fs, C3));
        u = u.fma(s, FloatVector.broadcast(fs, C2));
        u = u.fma(s, FloatVector.broadcast(fs, C1));
        u = u.fma(s, FloatVector.broadcast(fs, 0.5f));
        u = s.mul(s).fma(u, s).add(1f);
        IntVector half = q.lanewise(VectorOperators.ASHR, 1);
        u = u.mul(half.add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.mul(q.sub(half).add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.blend(0f, d.compare(VectorOperators.LT, -104f));
        u = u.blend(Float.POSITIVE_INFINITY, d.compare(VectorOperators.GT, 100f));
        sigmoidExp = u.blend(d.add(d), d.test(VectorOperators.IS_NAN));
      }
      one.div(one.add(sigmoidExp)).intoArray(sigmoidValues, sigmoidOffset + index);
      FloatVector value =
          FloatVector.fromArray(FloatVector.SPECIES_128, softplusValues, softplusOffset + index)
              .add(FloatVector.fromArray(FloatVector.SPECIES_128, bias, biasOffset + index));
      FloatVector softplusExp;
      {
        FloatVector d = value;

        var fs = d.species();
        FloatVector a =
            d.blend(
                0f, d.abs().compare(VectorOperators.GT, 104f).or(d.test(VectorOperators.IS_NAN)));
        FloatVector product = a.mul(RLOG2);
        IntVector sign = product.reinterpretAsInts().and(0x80000000);
        FloatVector rangeBias = sign.or(Float.floatToRawIntBits(0x1.8p23f)).reinterpretAsFloats();
        IntVector q =
            (IntVector) product.add(rangeBias).sub(rangeBias).convert(VectorOperators.F2I, 0);
        FloatVector fq = (FloatVector) q.convert(VectorOperators.I2F, 0);
        FloatVector s = fq.fma(FloatVector.broadcast(fs, -0.693145751953125f), a);
        s = fq.fma(FloatVector.broadcast(fs, -1.428606765330187045e-06f), s);
        FloatVector u = FloatVector.broadcast(fs, C5).fma(s, FloatVector.broadcast(fs, C4));
        u = u.fma(s, FloatVector.broadcast(fs, C3));
        u = u.fma(s, FloatVector.broadcast(fs, C2));
        u = u.fma(s, FloatVector.broadcast(fs, C1));
        u = u.fma(s, FloatVector.broadcast(fs, 0.5f));
        u = s.mul(s).fma(u, s).add(1f);
        IntVector half = q.lanewise(VectorOperators.ASHR, 1);
        u = u.mul(half.add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.mul(q.sub(half).add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.blend(0f, d.compare(VectorOperators.LT, -104f));
        u = u.blend(Float.POSITIVE_INFINITY, d.compare(VectorOperators.GT, 100f));
        softplusExp = u.blend(d.add(d), d.test(VectorOperators.IS_NAN));
      }
      FloatVector softplus;
      {
        FloatVector input = one.add(softplusExp);

        var sub = input.compare(VectorOperators.LT, Float.MIN_NORMAL);
        FloatVector d = input.blend(input.mul(0x1p64f), sub);
        IntVector e =
            d.mul(1f / .75f)
                .reinterpretAsInts()
                .lanewise(VectorOperators.LSHR, 23)
                .and(255)
                .sub(127);
        FloatVector m =
            d.reinterpretAsInts()
                .add(e.neg().lanewise(VectorOperators.LSHL, 23))
                .reinterpretAsFloats();
        e = e.blend(e.sub(64), sub.cast(e.species()));
        FloatVector ef = (FloatVector) e.convert(VectorOperators.I2F, 0);
        FloatVector sh = ef.mul(LNHI);
        FloatVector sl =
            FloatVector.broadcast(input.species(), LNLO)
                .fma(ef, FloatVector.broadcast(input.species(), LNHI).fma(ef, sh.neg()));
        FloatVector nh = m.add(-1f), nv = nh.add(1f);
        FloatVector nl = FloatVector.broadcast(input.species(), -1f).sub(nh.sub(nv)).add(m.sub(nv));
        FloatVector dh = m.add(1f), dv = dh.sub(1f);
        FloatVector dl = FloatVector.broadcast(input.species(), 1f).sub(dh.sub(dv)).add(m.sub(dv));
        FloatVector t = FloatVector.broadcast(input.species(), 1f).div(dh);
        FloatVector xh = nh.mul(t);
        FloatVector u = t.fma(nh, xh.neg());
        FloatVector v =
            dl.neg().fma(t, dh.neg().fma(t, FloatVector.broadcast(input.species(), 1f)));
        FloatVector xl = xh.fma(v, nl.fma(t, u));
        FloatVector x2 = xh.mul(xh);
        t =
            FloatVector.broadcast(input.species(), .3027294874f)
                .fma(x2, FloatVector.broadcast(input.species(), .3996108174f));
        t = t.fma(x2, FloatVector.broadcast(input.species(), .6666694880f));
        FloatVector yh = xh.mul(2f), yl = xl.mul(2f);
        FloatVector sum = sh.add(yh);
        sl = sh.sub(sum).add(yh).add(sl).add(yl);
        sh = sum;
        FloatVector y = x2.mul(xh).mul(t);
        sum = sh.add(y);
        sl = sh.sub(sum).add(y).add(sl);
        FloatVector r = sum.add(sl);
        r =
            r.blend(
                Float.POSITIVE_INFINITY,
                input.compare(VectorOperators.EQ, Float.POSITIVE_INFINITY));
        r =
            r.blend(
                Float.NaN,
                input.compare(VectorOperators.LT, 0f).or(input.test(VectorOperators.IS_NAN)));
        softplus = r.blend(Float.NEGATIVE_INFINITY, input.compare(VectorOperators.EQ, 0f));
      }

      softplus = softplus.blend(value, value.compare(VectorOperators.GT, threshold));
      softplus
          .mul(FloatVector.fromArray(FloatVector.SPECIES_128, scale, scaleOffset + index))
          .intoArray(scaledSoftplus, scaledSoftplusOffset + index);
    }
    for (; index < length; index++) {
      int sigmoidIndex = sigmoidOffset + index;
      float sigmoidValue = sigmoidValues[sigmoidIndex];
      sigmoidValues[sigmoidIndex] = 1.0f / (1.0f + scalarExp(-sigmoidValue));
      float softplusValue = softplusValues[softplusOffset + index] + bias[biasOffset + index];
      float softplus =
          softplusValue > 20.0f ? softplusValue : scalarLog(1.0f + scalarExp(softplusValue));
      scaledSoftplus[scaledSoftplusOffset + index] = scale[scaleOffset + index] * softplus;
    }
  }

  static void causalDepthwiseConv1dSilu(
      float[] values,
      int valuesOffset,
      float[] history,
      int historyOffset,
      float[] weights,
      int weightsOffset,
      int channels,
      int kernelSize) {
    int historyLength = kernelSize - 1;
    int channel = 0;
    int limit = FloatVector.SPECIES_128.loopBound(channels);
    FloatVector one = FloatVector.broadcast(FloatVector.SPECIES_128, 1.0f);
    for (; channel < limit; channel += FloatVector.SPECIES_128.length()) {
      FloatVector input =
          FloatVector.fromArray(FloatVector.SPECIES_128, values, valuesOffset + channel);
      FloatVector convolved =
          input.mul(
              FloatVector.fromArray(
                  FloatVector.SPECIES_128,
                  weights,
                  weightsOffset + historyLength * channels + channel));
      FloatVector previous =
          FloatVector.fromArray(FloatVector.SPECIES_128, history, historyOffset + channel);
      convolved =
          PanamaVectorUtilSupport.fma(
              previous,
              FloatVector.fromArray(FloatVector.SPECIES_128, weights, weightsOffset + channel),
              convolved);
      for (int tap = 1; tap < historyLength; tap++) {
        int historyIndex = historyOffset + tap * channels + channel;
        FloatVector current = FloatVector.fromArray(FloatVector.SPECIES_128, history, historyIndex);
        convolved =
            PanamaVectorUtilSupport.fma(
                current,
                FloatVector.fromArray(
                    FloatVector.SPECIES_128, weights, weightsOffset + tap * channels + channel),
                convolved);
        current.intoArray(history, historyIndex - channels);
      }
      input.intoArray(history, historyOffset + (historyLength - 1) * channels + channel);
      FloatVector convExp;
      {
        FloatVector d = convolved.neg();

        var fs = d.species();
        FloatVector a =
            d.blend(
                0f, d.abs().compare(VectorOperators.GT, 104f).or(d.test(VectorOperators.IS_NAN)));
        FloatVector product = a.mul(RLOG2);
        IntVector sign = product.reinterpretAsInts().and(0x80000000);
        FloatVector rangeBias = sign.or(Float.floatToRawIntBits(0x1.8p23f)).reinterpretAsFloats();
        IntVector q =
            (IntVector) product.add(rangeBias).sub(rangeBias).convert(VectorOperators.F2I, 0);
        FloatVector fq = (FloatVector) q.convert(VectorOperators.I2F, 0);
        FloatVector s = fq.fma(FloatVector.broadcast(fs, -0.693145751953125f), a);
        s = fq.fma(FloatVector.broadcast(fs, -1.428606765330187045e-06f), s);
        FloatVector u = FloatVector.broadcast(fs, C5).fma(s, FloatVector.broadcast(fs, C4));
        u = u.fma(s, FloatVector.broadcast(fs, C3));
        u = u.fma(s, FloatVector.broadcast(fs, C2));
        u = u.fma(s, FloatVector.broadcast(fs, C1));
        u = u.fma(s, FloatVector.broadcast(fs, 0.5f));
        u = s.mul(s).fma(u, s).add(1f);
        IntVector half = q.lanewise(VectorOperators.ASHR, 1);
        u = u.mul(half.add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.mul(q.sub(half).add(127).lanewise(VectorOperators.LSHL, 23).reinterpretAsFloats());
        u = u.blend(0f, d.compare(VectorOperators.LT, -104f));
        u = u.blend(Float.POSITIVE_INFINITY, d.compare(VectorOperators.GT, 100f));
        convExp = u.blend(d.add(d), d.test(VectorOperators.IS_NAN));
      }
      convolved.div(one.add(convExp)).intoArray(values, valuesOffset + channel);
    }
    for (; channel < channels; channel++) {
      float input = values[valuesOffset + channel];
      float convolved = input * weights[weightsOffset + historyLength * channels + channel];
      float previous = history[historyOffset + channel];
      convolved += previous * weights[weightsOffset + channel];
      for (int tap = 1; tap < historyLength; tap++) {
        int historyIndex = historyOffset + tap * channels + channel;
        float current = history[historyIndex];
        convolved += current * weights[weightsOffset + tap * channels + channel];
        history[historyIndex - channels] = current;
      }
      history[historyOffset + (historyLength - 1) * channels + channel] = input;
      values[valuesOffset + channel] = convolved / (1.0f + scalarExp(-convolved));
    }
  }

  private static float scalarExp(float d) {
    if (d < -104f) return 0f;
    if (d > 100f) return Float.POSITIVE_INFINITY;
    if (Float.isNaN(d)) return d + d;
    int q = (int) Math.rint(d * RLOG2);
    float s = Math.fma((float) q, -0.693145751953125f, d);
    s = Math.fma((float) q, -1.428606765330187045e-06f, s);
    float u = Math.fma(C5, s, C4);
    u = Math.fma(u, s, C3);
    u = Math.fma(u, s, C2);
    u = Math.fma(u, s, C1);
    u = Math.fma(u, s, 0.5f);
    u = 1f + Math.fma(s * s, u, s);
    int h = q >> 1;
    return (u * Float.intBitsToFloat((h + 127) << 23)) * Float.intBitsToFloat((q - h + 127) << 23);
  }

  private static float scalarLog(float d) {
    if (d == 0) return Float.NEGATIVE_INFINITY;
    if (d < 0 || Float.isNaN(d)) return Float.NaN;
    if (d == Float.POSITIVE_INFINITY) return d;
    boolean sub = d < Float.MIN_NORMAL;
    if (sub) d *= 0x1p64f;
    int e = ((Float.floatToRawIntBits(d * (1f / .75f)) >>> 23) & 255) - 127;
    float m = Float.intBitsToFloat(Float.floatToRawIntBits(d) + (-e << 23));
    if (sub) e -= 64;
    float sh = LNHI * e;
    float sl = Math.fma(LNLO, e, Math.fma(LNHI, e, -sh));
    float nh = -1f + m, nv = nh - (-1f);
    float nl = (-1f - (nh - nv)) + (m - nv);
    float dh = 1f + m, dv = dh - 1f;
    float dl = (1f - (dh - dv)) + (m - dv);
    float t = 1f / dh;
    float xh = nh * t;
    float u = Math.fma(t, nh, -xh);
    float v = Math.fma(-dl, t, Math.fma(-dh, t, 1f));
    float xl = Math.fma(xh, v, Math.fma(nl, t, u));
    float x2 = xh * xh;
    t = Math.fma(.3027294874f, x2, .3996108174f);
    t = Math.fma(t, x2, .6666694880f);
    float yh = xh * 2f, yl = xl * 2f;
    float sum = sh + yh;
    sl = (((sh - sum) + yh) + sl) + yl;
    sh = sum;
    float y = (x2 * xh) * t;
    sum = sh + y;
    sl = ((sh - sum) + y) + sl;
    return sum + sl;
  }
