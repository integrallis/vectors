package com.integrallis.vectors.core;

/**
 * Signed-byte vector distance and similarity kernels. Operates on vectors whose components are
 * signed 8-bit integers, typically products of scalar quantization.
 */
public interface ByteDistanceKernel {

  /** Computes the dot product of two signed byte vectors. */
  int dotProduct(byte[] a, byte[] b);

  /** Computes the squared Euclidean distance between two signed byte vectors. */
  int squareDistance(byte[] a, byte[] b);

  /** Computes the cosine similarity between two signed byte vectors. */
  float cosine(byte[] a, byte[] b);
}
